/**
 * DECORATIONS — the party dressing, 32x32, drawn against OBJECT_PALETTE.
 *
 * The light-emitting props follow one extra rule on top of the ramp/outline
 * conventions in food.ts: anything that actually gives off light is drawn with
 * a near-white core (`G`) that steps out through the material's own hue. A
 * flame painted in flat yellow reads as a yellow shape; a flame painted white
 * in the middle, gold around that, and amber at the rim reads as burning.
 *
 * Emissive props are deliberately drawn slightly BRIGHTER than looks right in
 * isolation, because the lighting layer multiplies darkness over the whole
 * board and would otherwise swallow them.
 */

